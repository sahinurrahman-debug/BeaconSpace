import { useApp } from "../ctx.js";
import { Empty, Icon, PageTitle } from "../ui.jsx";
import { NoRun } from "./NoRun.jsx";

export default function Report() {
  const { run, sel } = useApp();
  if (!run) return <NoRun />;
  const base = `/api/runs/${encodeURIComponent(sel)}`;
  return (
    <>
      <PageTitle title="Situation report" sub="One page in English, one in Nepali. Every number comes from the maps; no value is generated by a language model." />
      {run.files.sitrep ? (
        <>
          <div className="cols report" style={{ marginBottom: 16 }}>
            <div className="sp" />
            <a className="btn" href={`${base}/sitrep?download=true`} download="sitrep.html" title="Download the report as HTML"><Icon name="download" />HTML</a>
            {run.files.pdf ? <a className="btn" href={`${base}/sitrep.pdf`} download="sitrep.pdf" title="Download the report as PDF (English and Nepali)"><Icon name="download" />PDF</a> : <div />}
            <div className="sp" />
          </div>
          <iframe className="embed" sandbox="allow-popups allow-popups-to-escape-sandbox" title="Situation report" style={{ height: 1180 }} src={`${base}/sitrep`} />
        </>
      ) : (
        <Empty title="No situation report yet" body="This run has no <code>sitrep.html</code>. Re-run the analysis to generate it." />
      )}
    </>
  );
}
